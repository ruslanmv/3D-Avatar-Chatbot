#!/usr/bin/env node
// UN14. Refresh assets/wardrobe/garment-coverage.json from a Wardrobe Forge checkout: each
// garment template's id, name, category and the body regions it covers, verbatim from Forge's
// own assets/garment_templates/**/*.json, plus the colour names Forge prebuilds in.
//
//   node tools/wardrobe/sync-coverage.mjs <path to a 3D-Wardrobe-Forge checkout>
//
// Why a file and not a request: Forge's HTTP catalogue does not carry `coverage`, and serves a
// private look's template only to its operator, so the page cannot ask. The companion needs
// it to know what a look really covers — UN11: a "garter set" was taken for a whole outfit
// and her own cardigan stayed on, because completeness was guessed from names. Nothing here is
// edited by hand; rerun this when Forge's templates change. Forge is MIT-licensed; the facts
// copied are its template metadata, attributed in the file.
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const forge = process.argv[2];
if (!forge) {
    console.error('usage: node tools/wardrobe/sync-coverage.mjs <forge checkout>');
    process.exit(2);
}
const walk = (dir) =>
    readdirSync(dir).flatMap((name) => {
        const full = path.join(dir, name);
        return statSync(full).isDirectory() ? walk(full) : full.endsWith('.json') ? [full] : [];
    });
// How much of her hips a lingerie bottom covers: Forge's own BOTTOM_PRESETS (front and back
// coverage, 0-1, wardrobe/lingerie/specs.py), read through Forge's Python so nothing is copied
// by hand. A thong and briefs both cover "hips"; this is what tells them apart.
const presets = JSON.parse(
    execFileSync(
        'python3',
        ['-c', 'import json; from wardrobe.lingerie.specs import BOTTOM_PRESETS as P; print(json.dumps(P))'],
        { cwd: forge, encoding: 'utf8' }
    )
);
const share = (brief) => {
    const merged = { ...(presets[brief.preset] || {}), ...brief };
    const front = Number(merged.frontCoverage);
    const back = Number(merged.backCoverage);
    return Number.isFinite(front) && Number.isFinite(back) ? Math.round(((front + back) / 2) * 100) / 100 : null;
};
const templates = {};
for (const file of walk(path.join(forge, 'assets/garment_templates')).sort()) {
    const t = JSON.parse(readFileSync(file, 'utf8'));
    if (!t.id || !Array.isArray(t.coverage)) continue;
    const entry = { name: t.name, category: t.category, coverage: t.coverage };
    const brief = t.lingerie && t.lingerie.brief;
    const hips = brief ? share(brief) : null;
    if (hips !== null) entry.hipsShare = hips;
    templates[t.id] = entry;
}
const palettes = JSON.parse(readFileSync(path.join(forge, 'assets/catalog/palettes.json'), 'utf8'));
const colours = new Set();
const collect = (value) => {
    if (typeof value === 'string') colours.add(value.toLowerCase());
    else if (Array.isArray(value)) value.forEach(collect);
    else if (value && typeof value === 'object') Object.values(value).forEach(collect);
};
// `palettes` maps a palette name to its colour names; `categories`/`templates` name palettes.
for (const list of Object.values(palettes.palettes || {})) collect(list);
let commit = null;
try {
    commit = execFileSync('git', ['-C', forge, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
    commit = null;
}
const out = {
    about:
        'Garment template coverage from 3D-Wardrobe-Forge (MIT, github.com/ruslanmv/3D-Wardrobe-Forge, ' +
        'assets/garment_templates). Generated by tools/wardrobe/sync-coverage.mjs; never edit by hand.',
    source: { repository: 'ruslanmv/3D-Wardrobe-Forge', commit },
    // hipsShare: for a lingerie bottom, the share of her hips it covers (front and back averaged).
    regions: ['chest', 'waist', 'hips', 'upperLegs', 'lowerLegs', 'upperArms', 'lowerArms', 'shoulders', 'feet'],
    colours: [...colours].filter((c) => /^[a-z][a-z -]{1,24}$/.test(c)).sort(),
    templates,
};
writeFileSync(path.join(root, 'assets/wardrobe/garment-coverage.json'), JSON.stringify(out, null, 1) + '\n');
console.log(
    `${Object.keys(templates).length} templates, ${out.colours.length} colours → assets/wardrobe/garment-coverage.json`
);
