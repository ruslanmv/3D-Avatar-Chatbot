#!/usr/bin/env node
/**
 * AX16. Entry point for audits/vrm_animations — same procedure as the wardrobe
 * audit folder: run evidence into a stamped runs/ directory, leave the
 * committed inventory to tools/qa/animation-audit.mjs.
 *
 *   node audits/vrm_animations/run.mjs
 *   node audits/vrm_animations/run.mjs --avatar Vita --category sitting --shots all
 *   node audits/vrm_animations/run.mjs --full
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
const out = path.join(HERE, 'runs', stamp);

fs.mkdirSync(out, { recursive: true });

const extra = process.argv.slice(2);
const args = ['tools/qa/animation-audit.mjs', '--play', '--out', path.relative(ROOT, out), ...extra];

console.log('→ node', args.join(' '));
const r = spawnSync(process.execPath, args, { cwd: ROOT, stdio: 'inherit' });
if (r.status) process.exit(r.status || 1);

const readme = path.join(out, 'README.md');
fs.writeFileSync(
    readme,
    [
        `# Animation playback run ${stamp}`,
        '',
        'Generated by `node audits/vrm_animations/run.mjs`.',
        '',
        '- `all.csv` — every avatar × job',
        '- `<Avatar>.csv` — one file per avatar',
        '- `shots/` — JPEG frames for fail/warn (or `--shots all`)',
        '- `summary.json` — ok / warn / fail counts',
        '',
        'Inventory (committed): `quality-lab/data/3d/animations-audit.json`.',
        'Scorer: `tools/qa/AnimationPlaybackScorer.js`.',
        'UX contract: `audits/vrm_animations/AGENT.md`.',
        '',
    ].join('\n')
);
console.log('run written to', path.relative(ROOT, out));
